import "server-only";

export const ADMIN_SESSION_COOKIE_NAME = "admin_session";

export function adminSessionCookieOptions(expiresAt: Date) {
  return {
    httpOnly: true,
    sameSite: "lax" as const,
    secure: process.env.NODE_ENV === "production",
    path: "/",
    expires: expiresAt,
  };
}
